"""Build src/components/teletext/font.ts from the Bedstead font (CC0, John Harris's
outline version of the SAA5050 teletext character generator, with its character
rounding).

    npm pack @techandsoftware/teletext-fonts && tar xzf techandsoftware-teletext-fonts-*.tgz
    pip install fonttools
    python3 scripts/teletext-font.py package/bedstead.otf > src/components/teletext/font.ts

Each glyph is sampled at 12x20 pixels: the 6x10 dot cell at twice its resolution,
which is where the rounded diagonals sit. A pixel is set when its centre is inside the
outline.
"""

import base64
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

W, H = 12, 20
UNIT = 50  # font units per pixel (Bedstead: 100 per dot, cell 600 x 1000)
TOP = 800  # ascent

# The characters the decoder can draw: printable ASCII, Latin-1, Latin Extended-A, and
# the symbols of the Latin G0 national options and the Latin G2 set.
CHARS = (
    [chr(c) for c in range(0x21, 0x7F)]
    + [chr(c) for c in range(0xA1, 0x180) if c != 0xAD]
    + list("←↑→↓―‖½¼¾⅛⅜⅝⅞™♪₠‰αΩ■")
)


class Polys(BasePen):
    def __init__(self, gs):
        super().__init__(gs)
        self.polys, self.cur = [], []

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _curveToOne(self, a, b, c):  # Bedstead has none; approximate if present
        self.cur.append(c)

    def _closePath(self):
        self.polys.append(self.cur)
        self.cur = []

    _endPath = _closePath


def inside(polys, x, y):
    """Non-zero winding."""
    wind = 0
    for poly in polys:
        for (x0, y0), (x1, y1) in zip(poly, poly[1:] + poly[:1]):
            if y0 <= y < y1 or y1 <= y < y0:
                xi = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
                if xi > x:
                    wind += 1 if y1 > y0 else -1
    return wind != 0


def main():
    font = TTFont(sys.argv[1])
    cmap, gs = font.getBestCmap(), font.getGlyphSet()
    chars, data = [], bytearray()
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if not name:
            print(f"// missing {ch!r}", file=sys.stderr)
            continue
        pen = Polys(gs)
        gs[name].draw(pen)
        bits = 0
        for y in range(H):
            for x in range(W):
                if inside(pen.polys, x * UNIT + UNIT / 2, TOP - y * UNIT - UNIT / 2):
                    bits |= 1 << (y * W + x)
        chars.append(ch)
        data += bits.to_bytes(W * H // 8, "little")
    chars_js = "".join(chars).replace("\\", "\\\\").replace('"', '\\"')
    print("// Generated by scripts/teletext-font.py from Bedstead (CC0). Do not edit.")
    print("// Each glyph: 12x20 pixels, row by row, bit 0 first, 30 bytes.")
    print(f'export const GLYPH_CHARS = "{chars_js}";')
    print(f'export const GLYPH_DATA = "{base64.b64encode(bytes(data)).decode()}";')


main()
